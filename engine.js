function hyperWin(r,c){
  const wr=(r>=1&&r<=3)?0:(r>=5&&r<=7)?1:-1;
  const wc=(c>=1&&c<=3)?0:(c>=5&&c<=7)?1:-1;
  return (wr<0||wc<0)?-1:wr*2+wc;
}
