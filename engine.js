function shuffle(a,rng){for(let i=a.length-1;i>0;i--){const j=(rng()*(i+1))|0;const t=a[i];a[i]=a[j];a[j]=t;}return a;}
function neighbors(c){const r=(c/9)|0,k=c%9,out=[];if(r>0)out.push(c-9);if(r<8)out.push(c+9);if(k>0)out.push(c-1);if(k<8)out.push(c+1);return out;}
